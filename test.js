var E = require('./engine.js'), assert = require('assert');
assert.strictEqual(E.streakOf(['2026-10-16','2026-10-17','2026-10-18'], '2026-10-18'), 3);
assert.strictEqual(E.streakOf(['2026-10-16','2026-10-17'], '2026-10-18'), 2);
